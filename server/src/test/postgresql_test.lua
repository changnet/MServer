-- postgresql测试用例

if g_sharedata:get("__ENABLE_POSTGRESQL__") ~= "true" then
    print("ENABLE_POSTGRESQL not enable, postgresql_test skipped")
    return
end

local PostgreSQL = require "postgresql.postgresql"
local Json = require "util.json"

local max_insert = 10000

local db = nil -- Test.before里赋值

-- desc和mysql一样是关键字，用来测试标识符转义是否生效
local perf_test_stmt = [[
CREATE TABLE IF NOT EXISTS perf_test (
  auto_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id INTEGER NOT NULL DEFAULT 0,
  "desc" TEXT,
  amount INTEGER NOT NULL DEFAULT 0
)]]

local data_type_test_stmt = [[
CREATE TABLE IF NOT EXISTS data_type_test (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  bool_field BOOLEAN,
  int2_field SMALLINT,
  int4_field INTEGER,
  int8_field BIGINT,
  float4_field REAL,
  float8_field DOUBLE PRECISION,
  numeric_field NUMERIC(20,6),
  char_field CHAR(10),
  varchar_field VARCHAR(255),
  text_field TEXT,
  uuid_field UUID,
  jsonb_field JSONB,
  bytea_field BYTEA,
  date_field DATE,
  time_field TIME,
  timestamp_field TIMESTAMP,
  timestamptz_field TIMESTAMPTZ
)]]

-- 测试库可能还没建。PG里一个连接只能落在一个database上，没有mysql那种
-- db.tbl的跨库写法，所以先用默认的postgres库连上去建库，再连回来
local function ensure_database(conf)
    if 0 == db:connect(conf.ip, conf.port, conf.user, conf.pwd, conf.db) then
        return true
    end

    local e = db:connect(conf.ip, conf.port, conf.user, conf.pwd, "postgres")
    if 0 ~= e then
        printf("postgresql connect %s:%d fail: %s",
            conf.ip, conf.port, select(2, db:error()))
        return false
    end

    e = db:exec(string.format("CREATE DATABASE %s", conf.db))
    if 0 ~= e then
        printf("postgresql create database %s fail: %s",
            conf.db, select(2, db:error()))
        return false
    end
    db:disconnect()

    return 0 == db:connect(conf.ip, conf.port, conf.user, conf.pwd, conf.db)
end

Test.describe("postgresql test", function()
    Test.before(function()
        db = PostgreSQL()

        -- PG不需要thread_init
        local conf = g_setting.postgresql
        if not ensure_database(conf) then
            print("postgresql connect error", db:error())
            Test.assert(false)
        end

        Test.equal(db:exec("DROP TABLE IF EXISTS perf_test"), 0)
        Test.equal(db:exec("DROP TABLE IF EXISTS data_type_test"), 0)
        Test.equal(db:exec(perf_test_stmt), 0)
        Test.equal(db:exec(data_type_test_stmt), 0)
        Test.equal(db:exec(
            'CREATE UNIQUE INDEX IF NOT EXISTS "id_unique" ON perf_test (id)'), 0)
        Test.assert(db:read_database_struct())
    end)

    Test.it("postgresql base test", function()
        Test.equal(db:exec("DELETE FROM perf_test"), 0)

        -- 插入
        Test.equal(db:insert("perf_test", {{
            id = 1,
            desc = "base test item >>>>>>>>>>>>>>>>>>>><<<<<<<<<<<<<",
            amount = 1
        }}), 0)
        Test.equal(db:affected_rows(), 1)

        -- 更新超长字符串，测试底层缓冲区分配
        local desc = string.rep("longgggggggggggg", 512)
        Test.equal(db:update("perf_test", {amount = 99999, desc = desc},
            {id = 1}), 0)
        Test.equal(db:affected_rows(), 1)

        -- 删除一条不存在的记录，影响行数为0
        Test.equal(db:delete("perf_test", {id = 2}), 0)
        Test.equal(db:affected_rows(), 0)

        local e, rows = db:select("perf_test")
        Test.equal(e, 0)
        Test.equal(#rows, 1)
        Test.equal(rows[1].id, 1)
        Test.equal(rows[1].amount, 99999)
        Test.equal(rows[1].desc, desc)
    end)

    Test.it("postgresql upsert do update", function()
        Test.equal(db:exec("DELETE FROM perf_test"), 0)

        Test.equal(db:insert("perf_test", {{id = 1, amount = 1}}), 0)
        -- 主键冲突时按EXCLUDED更新
        Test.equal(db:insert("perf_test", {{id = 1, amount = 2}},
            {amount = PostgreSQL.EXCLUDED}, {"id"}), 0)

        local e, rows = db:select("perf_test", {"amount"}, {id = 1})
        Test.equal(e, 0)
        Test.equal(#rows, 1)
        Test.equal(rows[1].amount, 2)

        -- 普通值走转义，不需要手写EXCLUDED
        Test.equal(db:insert("perf_test", {{id = 1, amount = 3}},
            {amount = 888}, {"id"}), 0)
        e, rows = db:select("perf_test", {"amount"}, {id = 1})
        Test.equal(e, 0)
        Test.equal(rows[1].amount, 888)
    end)

    Test.it("postgresql upsert do nothing", function()
        Test.equal(db:exec("DELETE FROM perf_test"), 0)

        Test.equal(db:insert("perf_test", {{id = 1, amount = 1}}), 0)
        -- 冲突时忽略，行内容和影响行数都不变
        Test.equal(db:insert("perf_test", {{id = 1, amount = 2}}, nil, {"id"}), 0)
        Test.equal(db:affected_rows(), 0)

        local e, rows = db:select("perf_test", {"amount"}, {id = 1})
        Test.equal(e, 0)
        Test.equal(#rows, 1)
        Test.equal(rows[1].amount, 1)
    end)

    Test.it("postgresql returning id", function()
        -- 自增主键用 RETURNING 取回，不要用 PQoidValue
        Test.equal(db:exec("DELETE FROM perf_test"), 0)

        local e, rows = db:query(
            "INSERT INTO perf_test (id,amount) VALUES (999,1) RETURNING auto_id")
        Test.equal(e, 0)
        Test.equal(#rows, 1)
        Test.assert(rows[1].auto_id > 0)

        e, rows = db:select("perf_test", nil, {auto_id = rows[1].auto_id})
        Test.equal(e, 0)
        Test.equal(#rows, 1)
        Test.equal(rows[1].id, 999)
    end)

    Test.it("postgresql null", function()
        Test.equal(db:exec("DELETE FROM perf_test"), 0)

        -- desc没写，PG会用默认值（这里是NULL），读回来是nil
        Test.equal(db:insert("perf_test", {{id = 1, amount = 1}}), 0)

        local e, rows = db:select("perf_test")
        Test.equal(e, 0)
        Test.equal(rows[1].desc, nil)

        Test.equal(db:update("perf_test", {desc = "not null"}, {id = 1}), 0)
        e, rows = db:select("perf_test")
        Test.equal(e, 0)
        Test.equal(rows[1].desc, "not null")
    end)

    Test.it("postgresql escape", function()
        -- 单引号、双引号、反斜杠、百分号、中文，往返一致
        local str = [[a'b"c\d%e中文]]
        Test.equal(db:escape("a'b"), "a''b")

        Test.equal(db:exec("DELETE FROM perf_test"), 0)
        Test.equal(db:insert("perf_test", {{id = 1, desc = str}}), 0)

        -- desc是关键字，标识符必须加双引号
        local e, rows = db:select("perf_test", {"desc"})
        Test.equal(e, 0)
        Test.equal(#rows, 1)
        Test.equal(rows[1].desc, str)

        e, rows = db:query(string.format(
            "SELECT amount FROM perf_test WHERE %s = %s",
            db:escape_identifier("desc"), db:escape_literal(str)))
        Test.equal(e, 0)
        Test.equal(#rows, 1)
        Test.equal(rows[1].amount, 0)
    end)

    Test.it("postgresql bytea", function()
        -- 二进制(含\0)只能通过bytea读写，PG的字符串不接受\0
        local bin = string.char(0, 1, 2, 3, 255, 65, 66, 0)

        Test.equal(db:exec("DELETE FROM data_type_test"), 0)
        Test.equal(db:insert("data_type_test", {{bytea_field = bin}}), 0)

        local e, rows = db:select("data_type_test", {"bytea_field"})
        Test.equal(e, 0)
        Test.equal(#rows, 1)
        Test.equal(rows[1].bytea_field, bin)

        -- 转义接口本身也要能往返
        Test.equal(db:unescape_bytea(db:escape_bytea(bin)), bin)
    end)

    Test.it("postgresql data type", function()
        Test.equal(db:exec("DELETE FROM data_type_test"), 0)

        local row = {
            bool_field = true,
            int2_field = 32767,                  -- SMALLINT
            int4_field = 2147483647,             -- INTEGER
            int8_field = 9223372036854775807,    -- BIGINT
            float4_field = 3.14159,              -- REAL
            float8_field = 3.141592653589793,    -- DOUBLE PRECISION
            numeric_field = 12345678.9,          -- NUMERIC(20,6)
            char_field = "abcdefghij",           -- CHAR(10)是定长，正好10个字符
            varchar_field = "variable length string",
            text_field = "regular text content",
            uuid_field = "a0eebc99-9c0b-4ef8-bb6d-6bb9bd380a11",
            date_field = "2024-03-20",
            time_field = "14:30:00",
            timestamp_field = "2024-03-20 14:30:00",
        }
        Test.equal(db:insert("data_type_test", {row}), 0)

        local e, rows = db:select("data_type_test")
        Test.equal(e, 0)
        Test.equal(#rows, 1)

        -- id是自增列，其他字段没写，这里只比对写入的字段
        for k, v in pairs(row) do Test.equal(rows[1][k], v) end
        Test.equal(rows[1].bool_field, true) -- PG能区分boolean和整数

        -- jsonb会被PG规范化(补空格)，不能直接比字符串
        Test.equal(db:exec("DELETE FROM data_type_test"), 0)
        Test.equal(db:insert("data_type_test",
            {{jsonb_field = '{"name":"test","value":123}'}}), 0)
        e, rows = db:select("data_type_test", {"jsonb_field"})
        Test.equal(e, 0)
        local json = Json.decode(rows[1].jsonb_field)
        Test.equal(json.name, "test")
        Test.equal(json.value, 123)

        -- timestamptz带时区，格式取决于服务端的TimeZone设置
        Test.equal(db:exec("DELETE FROM data_type_test"), 0)
        Test.equal(db:insert("data_type_test",
            {{timestamptz_field = "2024-03-20 14:30:00+08"}}), 0)
        e, rows = db:select("data_type_test", {"timestamptz_field"})
        Test.equal(e, 0)
        Test.assert(string.match(rows[1].timestamptz_field, "^2024%-03%-20 14:30:00"))
    end)

    Test.it("postgresql wheres and fields", function()
        Test.equal(db:exec("DELETE FROM perf_test"), 0)
        Test.equal(db:insert("perf_test",
            {{id = 1, amount = 1}, {id = 2, amount = 2}, {id = 3, amount = 3}}), 0)

        local e, rows = db:select("perf_test", {"amount"}, {id = 2})
        Test.equal(e, 0)
        Test.equal(#rows, 1)
        Test.equal(rows[1].amount, 2)
        Test.equal(rows[1].id, nil) -- 只查了amount字段

        e, rows = db:select("perf_test", nil, {id = 3})
        Test.equal(e, 0)
        Test.equal(#rows, 1)
        Test.equal(rows[1].id, 3)
        Test.equal(rows[1].amount, 3)
    end)

    Test.it("postgresql index", function()
        Test.equal(db:exec("DELETE FROM perf_test"), 0)

        Test.equal(db:create_index("perf_test", "idx_amount", {"amount"},
            {if_not_exists = true}), 0)
        -- 重复建同名索引不报错
        Test.equal(db:create_index("perf_test", "idx_amount", {"amount"},
            {if_not_exists = true}), 0)

        Test.equal(db:exec('DROP INDEX IF EXISTS "uniq_amount"'), 0)
        Test.equal(db:create_index("perf_test", "uniq_amount", {"amount"},
            {unique = true}), 0)

        -- CONCURRENTLY不锁表，但不能放在事务块里，这里单独下发
        Test.equal(db:exec('DROP INDEX IF EXISTS "idx_conc"'), 0)
        Test.equal(db:create_index("perf_test", "idx_conc", {"amount"},
            {concurrently = true}), 0)

        Test.equal(db:exec('DROP INDEX IF EXISTS "idx_amount"'), 0)
        Test.equal(db:exec('DROP INDEX IF EXISTS "uniq_amount"'), 0)
        Test.equal(db:exec('DROP INDEX IF EXISTS "idx_conc"'), 0)
    end)

    Test.it("postgresql transaction", function()
        -- PG默认每条sql各自一个隐式事务，批量写要显式BEGIN、COMMIT
        Test.equal(db:exec("DELETE FROM perf_test"), 0)

        Test.equal(db:exec("BEGIN"), 0)
        Test.equal(db:insert("perf_test", {{id = 1, amount = 1}}), 0)
        Test.equal(db:exec("ROLLBACK"), 0)

        local e, rows = db:select("perf_test")
        Test.equal(e, 0)
        Test.equal(#rows, 0)

        Test.equal(db:exec("BEGIN"), 0)
        Test.equal(db:insert("perf_test", {{id = 2, amount = 2}}), 0)
        Test.equal(db:exec("COMMIT"), 0)

        e, rows = db:select("perf_test")
        Test.equal(e, 0)
        Test.equal(#rows, 1)
        Test.equal(rows[1].id, 2)
    end)

    Test.it("postgresql error handling", function()
        local e = db:query("SELECT * FROM no_such_table")
        Test.assert(0 ~= e)

        local e1, msg = db:error()
        Test.assert(0 ~= e1)
        Test.assert(msg and #msg > 0)
        Test.print(msg)

        -- 出错后连接仍然可用
        Test.equal(db:ping(), 0)
        Test.equal(db:exec("DELETE FROM perf_test"), 0)
    end)

    Test.it(string.format("postgresql perf %d insert", max_insert), function()
        Test.equal(db:exec("DELETE FROM perf_test"), 0)

        local rows = {}
        for i = 1, max_insert do
            rows[i] = {
                id = i,
                amount = i * 10,
                desc = "just test itemmmmmmmmmmmmmmmmmmmmmmmmmmmmmmmm"
            }
        end
        Test.equal(db:insert("perf_test", rows), 0)

        local e, got = db:select("perf_test")
        Test.equal(e, 0)
        Test.equal(#got, max_insert)
    end)

    Test.after(function()
        db:exec("DROP TABLE IF EXISTS perf_test")
        db:exec("DROP TABLE IF EXISTS data_type_test")
        db:disconnect()
    end)
end)
